-- REDUNDANCY-01 parity fingerprint, part 1: one read-only SELECT that describes the database a restore must match.
-- It runs unchanged under psql (hosted source, owned-server target) and PGlite (local tests), and writes nothing.
-- Scope comes from session settings so this file needs no templating:
--   set tapuai.parity_schemas = 'auto';       -- comma list of application schemas; 'auto' (default) = every schema
--                                             -- that is not PostgreSQL's or Supabase's (today public, fan_zone_private)
--   set tapuai.parity_hash_rows = 'on';       -- 'off' = row counts only (faster on large tables)
-- The `rows_sql` key is a second SELECT generated by the database itself, with identifiers quoted by format('%I'),
-- that counts (and optionally hashes) every in-scope table plus the Supabase service tables a restore carries
-- (exact hashes of all nonextension Auth data tables, Storage counts, migration history). Auth hashing is never disabled.
-- Version-2 coverage distinguishes missing Auth tables from detected/hashed data; parity.py runs and merges rows.
-- Extension-owned objects are left out: they belong to the target stack, and their presence is checked separately.
-- `service` describes what the app attaches to Supabase's own tables (policies on storage.objects, the signup trigger
-- on auth.users, realtime policies) and which functions the service schemas hold. Run on a bare target stack before
-- a restore, it tells toc_review.py what the stack already provides; after a restore, parity checks the app's
-- attachments came back. Exact service definitions/security/effective grants also detect incompatible stack upgrades.
with managed(nspname) as (
  values ('auth'), ('storage'), ('realtime'), ('_realtime'), ('extensions'), ('graphql'), ('graphql_public'), ('vault'),
         ('pgsodium'), ('pgsodium_masks'), ('supabase_functions'), ('supabase_migrations'), ('net'), ('pgbouncer'), ('cron'),
         ('pgtle'), ('_analytics'), ('topology'), ('tiger'), ('tiger_data')
),
requested as (
  select coalesce(nullif(current_setting('tapuai.parity_schemas', true), ''), 'auto') as value
),
scope as (
  select trim(s) as nspname
  from requested, unnest(string_to_array(requested.value, ',')) as s
  where requested.value <> 'auto' and trim(s) <> ''
  union
  select n.nspname from requested, pg_namespace n
  where requested.value = 'auto' and n.nspname not in (select nspname from managed)
    and n.nspname not in ('pg_catalog', 'information_schema') and n.nspname not like 'pg\_toast%' and n.nspname not like 'pg\_temp%'
    and n.oid not in (select objid from pg_depend where deptype = 'e')
),
ns as (
  select n.oid, n.nspname from pg_namespace n join scope s on s.nspname = n.nspname
),
ext_owned as (
  select objid from pg_depend where deptype = 'e'
),
rels as (
  select c.oid, n.nspname, c.relname, c.relkind, c.relrowsecurity, c.relforcerowsecurity,
         pg_get_userbyid(c.relowner) as owner, c.relacl,
         format('%s.%s', n.nspname, c.relname) as key
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where c.relkind in ('r', 'p', 'v', 'm', 'S') and c.oid not in (select objid from ext_owned)
    and (n.nspname in (select nspname from scope) or n.nspname in (select nspname from managed))
),
grants as (
  select r.oid, jsonb_agg(distinct format('%s:%s', case when a.grantee = 0 then 'PUBLIC' else pg_get_userbyid(a.grantee) end, a.privilege_type)) as list
  from rels r cross join lateral aclexplode(r.relacl) a
  group by r.oid
),
tables as (
  select r.key, jsonb_build_object(
    'kind', r.relkind,
    'owner', r.owner,
    'rls', r.relrowsecurity,
    'forceRls', r.relforcerowsecurity,
    'columns', (select coalesce(jsonb_agg(format('%s %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                       case when a.attnotnull then ' not null' else '' end,
                       coalesce(' default ' || pg_get_expr(d.adbin, d.adrelid), '')) order by a.attnum), '[]'::jsonb)
                from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
                where a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped),
    'constraints', (select coalesce(jsonb_object_agg(con.conname, pg_get_constraintdef(con.oid)), '{}'::jsonb)
                    from pg_constraint con where con.conrelid = r.oid),
    'indexes', (select coalesce(jsonb_object_agg(i.relname, pg_get_indexdef(x.indexrelid)), '{}'::jsonb)
                from pg_index x join pg_class i on i.oid = x.indexrelid where x.indrelid = r.oid),
    'triggers', (select coalesce(jsonb_object_agg(t.tgname, jsonb_build_object('def', pg_get_triggerdef(t.oid), 'enabled', t.tgenabled)), '{}'::jsonb)
                 from pg_trigger t where t.tgrelid = r.oid and not t.tgisinternal),
    'policies', (select coalesce(jsonb_object_agg(p.polname, jsonb_build_object(
                    'cmd', p.polcmd, 'permissive', p.polpermissive,
                    'roles', (select coalesce(jsonb_agg(case when rid = 0 then 'PUBLIC' else pg_get_userbyid(rid) end order by 1), '[]'::jsonb) from unnest(p.polroles) rid),
                    'using', pg_get_expr(p.polqual, p.polrelid), 'check', pg_get_expr(p.polwithcheck, p.polrelid))), '{}'::jsonb)
                 from pg_policy p where p.polrelid = r.oid),
    'definition', case when r.relkind in ('v', 'm') then md5(pg_get_viewdef(r.oid, true)) end,
    'grants', coalesce((select g.list from grants g where g.oid = r.oid), '[]'::jsonb),
    'privilegeDetails', (select coalesce(jsonb_agg(jsonb_build_object(
            'grantee', case when a.grantee = 0 then 'PUBLIC' else pg_get_userbyid(a.grantee) end,
            'grantor', pg_get_userbyid(a.grantor), 'privilege', a.privilege_type, 'grantOption', a.is_grantable)
            order by case when a.grantee = 0 then 'PUBLIC' else pg_get_userbyid(a.grantee) end,
                     pg_get_userbyid(a.grantor), a.privilege_type, a.is_grantable), '[]'::jsonb)
          from aclexplode(coalesce(r.relacl, acldefault('r', (select relowner from pg_class where oid = r.oid)))) a)
  ) as body
  from rels r where r.relkind <> 'S'
),
function_bodies as (
  select format('%s.%s(%s)', n.nspname, p.proname, pg_get_function_identity_arguments(p.oid)) as key,
         jsonb_build_object(
           'kind', p.prokind,
           'returns', pg_get_function_result(p.oid),
           'language', l.lanname,
           'securityDefiner', p.prosecdef,
           'volatility', p.provolatile,
           'config', coalesce(to_jsonb(p.proconfig), '[]'::jsonb),
           'bodyMd5', md5(coalesce(p.prosrc, '')),
           'definition', case when p.prokind <> 'a' then pg_get_functiondef(p.oid) end,
           'binary', p.probin,
           'strict', p.proisstrict,
           'leakproof', p.proleakproof,
           'parallel', p.proparallel,
           'owner', pg_get_userbyid(p.proowner),
           'grants', (select coalesce(jsonb_agg(jsonb_build_object(
                         'grantee', case when a.grantee = 0 then 'PUBLIC' else pg_get_userbyid(a.grantee) end,
                         'grantor', pg_get_userbyid(a.grantor), 'privilege', a.privilege_type,
                         'grantOption', a.is_grantable)
                         order by case when a.grantee = 0 then 'PUBLIC' else pg_get_userbyid(a.grantee) end,
                                  pg_get_userbyid(a.grantor), a.privilege_type, a.is_grantable), '[]'::jsonb)
                       from aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a),
           'execute', (select coalesce(jsonb_agg(distinct case when a.grantee = 0 then 'PUBLIC' else pg_get_userbyid(a.grantee) end
                                         order by case when a.grantee = 0 then 'PUBLIC' else pg_get_userbyid(a.grantee) end), '[]'::jsonb)
                       from aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a where a.privilege_type = 'EXECUTE')
         ) as body
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_language l on l.oid = p.prolang
  where p.oid not in (select objid from ext_owned)
    and (n.nspname in (select nspname from scope) or n.nspname in (select nspname from managed))
),
funcs as (
  select f.* from function_bodies f where split_part(f.key, '.', 1) in (select nspname from scope)
),
service_funcs as (
  select f.* from function_bodies f where split_part(f.key, '.', 1) in (select nspname from managed)
),
auth_targets as (
  -- Discover every Auth data table rather than assuming one GoTrue version's sessions/MFA/flow catalog.
  select n.nspname, c.relname, format('%s.%s', n.nspname, c.relname) as key
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'auth' and c.relkind in ('r', 'p') and c.oid not in (select objid from ext_owned)
),
auth_seqs as (
  -- Sequence state is not a table row: capture direct last_value/is_called separately, never call nextval.
  select c.oid, n.nspname, c.relname, format('%s.%s', n.nspname, c.relname) as key,
         jsonb_build_object(
           'dataType', format_type(s.seqtypid, null), 'start', s.seqstart, 'increment', s.seqincrement,
           'min', s.seqmin, 'max', s.seqmax, 'cache', s.seqcache, 'cycle', s.seqcycle,
           'owner', pg_get_userbyid(c.relowner),
           'stateRowKey', format('auth-sequence:%s.%s', n.nspname, c.relname),
           'ownedBy', (select coalesce(jsonb_agg(format('%s.%s.%s', rn.nspname, rc.relname, a.attname)
                                               order by rn.nspname, rc.relname, a.attname), '[]'::jsonb)
                       from pg_depend d join pg_class rc on rc.oid = d.refobjid
                       join pg_namespace rn on rn.oid = rc.relnamespace
                       join pg_attribute a on a.attrelid = d.refobjid and a.attnum = d.refobjsubid
                       where d.classid = 'pg_class'::regclass and d.refclassid = 'pg_class'::regclass
                         and d.objid = c.oid and d.deptype in ('a', 'i')),
           'grants', (select coalesce(jsonb_agg(jsonb_build_object(
                         'grantee', case when acl.grantee = 0 then 'PUBLIC' else pg_get_userbyid(acl.grantee) end,
                         'grantor', pg_get_userbyid(acl.grantor), 'privilege', acl.privilege_type,
                         'grantOption', acl.is_grantable)
                         order by case when acl.grantee = 0 then 'PUBLIC' else pg_get_userbyid(acl.grantee) end,
                                  pg_get_userbyid(acl.grantor), acl.privilege_type, acl.is_grantable), '[]'::jsonb)
                      from aclexplode(coalesce(c.relacl, acldefault('S', c.relowner))) acl)
         ) as body
  from pg_sequence s join pg_class c on c.oid = s.seqrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'auth' and c.oid not in (select objid from ext_owned)
),
seqs as (
  select format('%s.%s', s.schemaname, s.sequencename) as key, s.last_value
  from pg_sequences s join scope sc on sc.nspname = s.schemaname
),
enums as (
  select format('%s.%s', n.nspname, t.typname) as key, jsonb_agg(e.enumlabel order by e.enumsortorder) as labels
  from pg_type t join ns n on n.oid = t.typnamespace join pg_enum e on e.enumtypid = t.oid
  group by n.nspname, t.typname
),
row_targets as (
  -- Application tables in scope, then the service tables a full restore carries, only where they exist.
  select key, format('select %L::text as key, count(*)::bigint as row_count, %s as digest from %I.%I t',
                     key,
                     case when current_setting('tapuai.parity_hash_rows', true) = 'off'
                                    and key not in (select key from auth_targets) then 'null::text'
                          else 'coalesce(md5(string_agg(md5(t::text), '''' order by md5(t::text))), '''')' end,
                     nspname, relname) as q
  from rels where relkind in ('r', 'p', 'm') and nspname in (select nspname from scope)
  union all
  select key, format('select %L::text as key, count(*)::bigint as row_count, coalesce(md5(string_agg(md5(t::text), '''' order by md5(t::text))), '''') as digest from %I.%I t',
                     key, nspname, relname)
  from auth_targets where nspname not in (select nspname from scope)
  union all
  select body->>'stateRowKey', format('select %L::text as key, last_value::bigint as row_count, is_called::text as digest from %I.%I',
                                    body->>'stateRowKey', nspname, relname)
  from auth_seqs
  union all
  select svc, format('select %L::text as key, count(*)::bigint as row_count, null::text as digest from %s', svc, svc)
  from unnest(array['storage.buckets', 'storage.objects']) as svc
  where to_regclass(svc) is not null and split_part(svc, '.', 1) not in (select nspname from scope)
  union all
  select 'supabase_migrations.schema_migrations',
         'select ''supabase_migrations.schema_migrations''::text as key, count(*)::bigint as row_count, string_agg(version::text, '','' order by version::text) as digest from supabase_migrations.schema_migrations'
  where to_regclass('supabase_migrations.schema_migrations') is not null
)
select jsonb_build_object(
  'format', 'tapuai-parity/1',
  'coverage', jsonb_build_object(
    'version', 2,
    'applicationFunctionDefinitions', true,
    'applicationFunctionKeys', (select coalesce(jsonb_agg(key order by key), '[]'::jsonb) from funcs),
    'applicationFunctionCount', (select count(*) from funcs),
    'serviceFunctionDefinitions', true,
    'serviceFunctionKeys', (select coalesce(jsonb_agg(key order by key), '[]'::jsonb) from service_funcs),
    'serviceFunctionCount', (select count(*) from service_funcs),
    'extensionOwnedFunctionsExcluded', true,
    'serviceTableDefinitions', true,
    'serviceTableKeys', (select coalesce(jsonb_agg(key order by key), '[]'::jsonb)
                        from tables where split_part(key, '.', 1) in (select nspname from managed)),
    'serviceTableCount', (select count(*) from tables where split_part(key, '.', 1) in (select nspname from managed)),
    'authSequenceDefinitions', true,
    'authSequenceKeys', (select coalesce(jsonb_agg(key order by key), '[]'::jsonb) from auth_seqs),
    'authSequenceCount', (select count(*) from auth_seqs),
    'serviceFunctionSchemas', (select coalesce(jsonb_agg(n.nspname order by n.nspname), '[]'::jsonb)
                               from pg_namespace n where n.nspname in (select nspname from managed)),
    'unsupportedServiceFunctionKinds', (select coalesce(jsonb_agg(key order by key), '[]'::jsonb)
                                       from service_funcs where body->>'definition' is null),
    'authData', jsonb_build_object(
      'mode', 'exact-row-hash',
      'requiredTables', jsonb_build_array('auth.users', 'auth.identities', 'auth.mfa_factors'),
      'missingRequiredTables', (select coalesce(jsonb_agg(k order by k), '[]'::jsonb)
                               from unnest(array['auth.users', 'auth.identities', 'auth.mfa_factors']) k
                               where k not in (select key from auth_targets)),
      'hashedTables', (select coalesce(jsonb_agg(key order by key), '[]'::jsonb) from auth_targets),
      'detectedAuthTables', (select coalesce(jsonb_agg(key order by key), '[]'::jsonb) from auth_targets),
      'detectedMfaTables', (select coalesce(jsonb_agg(key order by key), '[]'::jsonb)
                          from auth_targets where relname like 'mfa\_%'),
      'absentKnownMfaTables', (select coalesce(jsonb_agg(k order by k), '[]'::jsonb)
                             from unnest(array['auth.mfa_factors', 'auth.mfa_challenges', 'auth.mfa_amr_claims']) k
                             where k not in (select key from auth_targets))
    )
  ),
  'meta', jsonb_build_object(
    'serverVersionNum', current_setting('server_version_num')::int,
    'currentUser', current_user,
    'superuser', current_setting('is_superuser') = 'on',
    'bypassRls', (select rolbypassrls from pg_roles where rolname = current_user),
    'schemas', (select coalesce(jsonb_agg(nspname order by nspname), '[]'::jsonb) from scope),
    'missingSchemas', (select coalesce(jsonb_agg(s.nspname order by s.nspname), '[]'::jsonb) from scope s where s.nspname not in (select nspname from ns)),
    'hashRows', coalesce(current_setting('tapuai.parity_hash_rows', true), 'on') <> 'off'
  ),
  'extensions', (select coalesce(jsonb_object_agg(e.extname, jsonb_build_object('version', e.extversion, 'schema', n.nspname)), '{}'::jsonb)
                 from pg_extension e join pg_namespace n on n.oid = e.extnamespace),
  'tables', (select coalesce(jsonb_object_agg(key, body), '{}'::jsonb) from tables
             where split_part(key, '.', 1) in (select nspname from scope)),
  'functions', (select coalesce(jsonb_object_agg(key, body), '{}'::jsonb) from funcs),
  'sequences', (select coalesce(jsonb_object_agg(key, last_value), '{}'::jsonb) from seqs),
  'sequenceGrants', (select coalesce(jsonb_object_agg(r.key, coalesce(g.list, '[]'::jsonb)), '{}'::jsonb)
                     from rels r left join grants g on g.oid = r.oid where r.relkind = 'S'
                       and r.nspname in (select nspname from scope)),
  'enums', (select coalesce(jsonb_object_agg(key, labels), '{}'::jsonb) from enums),
  'publications', (select coalesce(jsonb_object_agg(pubname, tabs), '{}'::jsonb) from (
                     select pubname, jsonb_agg(format('%s.%s', schemaname, tablename) order by schemaname, tablename) as tabs
                     from pg_publication_tables group by pubname) pub),
  'service', jsonb_build_object(
    'authSequences', (select coalesce(jsonb_object_agg(key, body), '{}'::jsonb) from auth_seqs),
    'tables', (select coalesce(jsonb_object_agg(key, body - 'triggers' - 'policies'), '{}'::jsonb) from tables
               where split_part(key, '.', 1) in (select nspname from managed)),
    'attachments', (select coalesce(jsonb_object_agg(format('%s.%s', n.nspname, c.relname), jsonb_build_object(
        'rls', c.relrowsecurity,
        'policies', (select coalesce(jsonb_object_agg(p.polname, jsonb_build_object('cmd', p.polcmd, 'permissive', p.polpermissive,
                       'roles', (select coalesce(jsonb_agg(case when rid = 0 then 'PUBLIC' else pg_get_userbyid(rid) end order by 1), '[]'::jsonb) from unnest(p.polroles) rid),
                       'using', pg_get_expr(p.polqual, p.polrelid), 'check', pg_get_expr(p.polwithcheck, p.polrelid))), '{}'::jsonb)
                     from pg_policy p where p.polrelid = c.oid),
        'triggers', (select coalesce(jsonb_object_agg(t.tgname, jsonb_build_object('def', pg_get_triggerdef(t.oid), 'enabled', t.tgenabled)), '{}'::jsonb)
                     from pg_trigger t where t.tgrelid = c.oid and not t.tgisinternal))), '{}'::jsonb)
      from pg_class c join pg_namespace n on n.oid = c.relnamespace
      where n.nspname in (select nspname from managed) and n.nspname <> 'supabase_migrations' and c.relkind in ('r', 'p')
        and c.oid not in (select objid from pg_depend where deptype = 'e')),
    'functions', (select coalesce(jsonb_object_agg(key, body), '{}'::jsonb) from service_funcs)
  ),
  'rows_sql', (select string_agg(q, E'\nunion all\n' order by key) from row_targets)
) as fingerprint;
